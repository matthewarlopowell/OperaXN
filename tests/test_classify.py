"""Classifier, grouper, and metadata-parser unit coverage."""
import os

import pandas as pd
import pytest

import core

import _builders

SYN_FILES = {
    "/data/sample_123456.nxs": "o1",
    "/data/sample_123456.hdf": "o2",
    "/data/sample_123456_integration_00.xy": "o3",
    "/data/other_777777.nxs": "o4",
    "/data/orphan_999999.hdf": "o5",
    "/data/sample_123456_extra.xy": "o6",
}


@pytest.fixture
def syn_groups():
    """SynchrotronFileGrouper output over the fixed synchrotron file mix."""
    return core.SynchrotronFileGrouper().group_files(dict(SYN_FILES))


@pytest.mark.parametrize("scan_id, key, expected", [
    pytest.param("123456", "nxs", "/data/sample_123456.nxs", id="anchored-nxs"),
    pytest.param("123456", "hdf", "/data/sample_123456.hdf", id="anchored-hdf"),
    pytest.param("777777", "nxs", "/data/other_777777.nxs", id="lone-nxs-own-group"),
])
def test_synchrotron_grouping(syn_groups, scan_id, key, expected):
    """A .nxs anchors each group; same-ID files join; a lone .nxs still groups."""
    assert syn_groups.get(scan_id, {}).get(key) == expected, str(syn_groups.get(scan_id))


def test_synchrotron_orphan_hdf_stays_ungrouped(syn_groups):
    """An .hdf with no matching .nxs anchor never forms a group."""
    assert "999999" not in syn_groups, str(syn_groups)


def test_synchrotron_integration_xy_joins_group():
    """An _integration_ .xy maps back to its scan ID and joins the anchored group."""
    files = {k: v for k, v in SYN_FILES.items() if k != "/data/sample_123456_extra.xy"}
    groups = core.SynchrotronFileGrouper().group_files(files)
    assert groups["123456"].get("xy") == "/data/sample_123456_integration_00.xy", \
        str(groups.get("123456"))


def test_synchrotron_trailing_id_xy_joins_group(syn_groups):
    """A plain trailing-ID .xy also joins its group; the last file grouped wins the slot."""
    assert syn_groups.get("123456", {}).get("xy") == "/data/sample_123456_extra.xy", \
        str(syn_groups.get("123456"))


def test_neutron_metadata_parse(tmp_path):
    """The builder logbook line parses to one row with scan_id and datetime start/end."""
    path = tmp_path / "logbook.txt"
    path.write_text(_builders.LOGBOOK_LINE + "\n")
    df = core.NeutronMetadataParser.parse(str(path))
    assert df is not None and len(df) == 1
    assert {"scan_id", "start_time", "end_time"} <= set(df.columns), str(df.columns)
    row = df.iloc[0]
    assert row["scan_id"] == "123456", f"got {row['scan_id']}"
    assert row["start_time"] == pd.Timestamp("2024-02-05 10:00:00"), f"got {row['start_time']}"
    assert row["end_time"] == pd.Timestamp("2024-02-05 10:30:00"), f"got {row['end_time']}"


def test_neutron_file_grouping(tmp_path):
    """Builder bank files group as scan -> measurement -> tof/d paths."""
    _builders.write_neutron_banks(str(tmp_path))
    files = [str(tmp_path / name) for name in sorted(os.listdir(tmp_path))]
    groups = core.NeutronFileGrouper().group_neutron_files(files)
    assert set(groups.keys()) == {"123456"}, str(groups)
    assert set(groups["123456"].keys()) == {"1", "2"}, str(groups["123456"])
    for meas in ("1", "2"):
        assert set(groups["123456"][meas].keys()) == {"tof", "d"}, str(groups["123456"][meas])
        assert groups["123456"][meas]["tof"].endswith(f"123456-{meas}-0.dat")
        assert groups["123456"][meas]["d"].endswith(f"123456-{meas}-d-0.dat")


